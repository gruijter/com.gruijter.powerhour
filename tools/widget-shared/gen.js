'use strict';

const fs = require('fs');
const path = require('path');

// Shared files of the widgets, copied into widgets/<id>/public/: flow.js and flow.css (the node
// diagram, one source here), and icons.js: the driver icons without the app badge, so both look the
// same; black becomes currentColor, so a node colours its icon.
const ROOT = path.join(__dirname, '../..');
const SOURCES = {
  grid: 'drivers/grid/assets/icon.svg',
  solar: 'drivers/solar/assets/icon.svg',
  battery: 'drivers/battery/assets/icon.svg',
  ev: 'drivers/evCharger/assets/icon.svg',
  gas: 'drivers/gas/assets/icon.svg',
  home: 'assets/measure_watt_home.svg', // no home driver: the Grid Monitor's home power icon
  price: 'drivers/price/assets/icon.svg',
  appliance: 'drivers/power/assets/icon.svg',
};
const WIDGETS = ['power_flow', 'energy', 'plan'];
const DIAGRAM = ['power_flow', 'energy']; // also get flow.js and flow.css

// Inner markup of one icon in a 100 x 100 box.
const glyph = (file) => {
  const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const box = src.match(/viewBox="0 0 (\d+) (\d+)"/);
  let inner = src.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/<defs>[\s\S]*?<\/defs>/g, '')
    .replace(/\s*mask="url\(#pbth-badge-cut\)"/g, '')
    .replace(/<circle cx="79" cy="79" r="16"[^>]*\/>\s*<g fill="#000">[\s\S]*?<\/g>/, '') // badge
    .replace(/\s+id="[^"]*"/g, '')
    .replace(/#000000|#000\b/g, 'currentColor')
    .replace(/\s*\n\s*/g, ' ')
    .trim();
  const size = box ? Number(box[1]) : 100;
  if (size !== 100) inner = `<g transform="scale(${100 / size})">${inner}</g>`;
  // SVG fills an element without a fill black: those parts take the node colour too.
  return `<g fill="currentColor">${inner}</g>`;
};

const icons = {};
Object.entries(SOURCES).forEach(([name, file]) => {
  icons[name] = glyph(file);
});
// PBTH_PLACE_ICON centres an icon on its drawn shape: the driver icons sit off-centre in their box
// (room for the badge). Measured once per icon in a hidden svg (getBBox needs it rendered).
const PLACE = `
window.PBTH_PLACE_ICON = function (parent, id, cx, cy, size, color) {
  var NS = 'http://www.w3.org/2000/svg';
  var boxes = window.PBTH_ICON_BOXES || (window.PBTH_ICON_BOXES = {});
  var markup = window.PBTH_ICONS[id] || '';
  if (!boxes[id]) {
    var m = document.createElementNS(NS, 'svg');
    m.setAttribute('style', 'position:absolute;left:-9999px;top:0;width:100px;height:100px;visibility:hidden');
    var probe = document.createElementNS(NS, 'g');
    probe.innerHTML = markup;
    m.appendChild(probe);
    document.body.appendChild(m);
    var b = probe.getBBox();
    document.body.removeChild(m);
    boxes[id] = b.width && b.height ? { x: b.x, y: b.y, w: b.width, h: b.height } : { x: 0, y: 0, w: 100, h: 100 };
  }
  var box = boxes[id];
  var k = size / Math.max(box.w, box.h);
  var g = document.createElementNS(NS, 'g');
  g.setAttribute('transform', 'translate(' + (cx - (box.x + box.w / 2) * k).toFixed(2) + ' ' + (cy - (box.y + box.h / 2) * k).toFixed(2) + ') scale(' + k.toFixed(4) + ')');
  g.setAttribute('style', 'color:' + color);
  g.innerHTML = markup;
  parent.appendChild(g);
  return g;
};
`;
const js = `// Generated by tools/widget-shared/gen.js from the driver icons - do not edit.\nwindow.PBTH_ICONS = ${JSON.stringify(icons, null, 2)};\n${PLACE}`;
WIDGETS.forEach((w) => {
  const dir = path.join(ROOT, 'widgets', w, 'public');
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'icons.js'), js);
  (DIAGRAM.includes(w) ? ['flow.js', 'flow.css'] : []).forEach((f) => {
    const note = f.endsWith('.css') ? '/* Copy of tools/widget-shared/' : '// Copy of tools/widget-shared/';
    const end = f.endsWith('.css') ? ' - edit there, run gen.js. */' : ' - edit there, run gen.js.';
    fs.writeFileSync(path.join(dir, f), `${note}${f}${end}\n${fs.readFileSync(path.join(__dirname, f), 'utf8')}`);
  });
});
// eslint-disable-next-line no-console
console.log('icons.js, flow.js, flow.css written for', WIDGETS.join(', '));
